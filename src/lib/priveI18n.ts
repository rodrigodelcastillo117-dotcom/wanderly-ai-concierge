export const PRIVE_LOCALE: Record<PriveLang, string> = { es: "es-MX", en: "en-US" };

/** "es-MX" → es, "en_GB" → en, "Español"/"English" → es/en; cualquier otro → null. */
export function langFromTag(tag: string | null | undefined): PriveLang | null {
  const t = String(tag ?? "").trim().toLowerCase();
  if (!t) return null;
  const base = t.split(/[-_]/)[0];
  if (base === "es" || t.startsWith("espa") || t === "spanish") return "es";
  if (base === "en" || t === "english" || t.startsWith("ingl")) return "en";
  return null;
}

export function resolvePriveLang(opts: { profile?: string | null; languages?: readonly (string | null | undefined)[] | null } = {}): PriveLang {
  const fromProfile = langFromTag(opts.profile);
  if (fromProfile) return fromProfile;
  for (const l of opts.languages ?? []) {
    const r = langFromTag(l);
    if (r) return r;
  }
  return "es";
}

export function browserLanguages(): string[] {
  if (typeof navigator === "undefined") return [];
  const list = Array.isArray(navigator.languages) && navigator.languages.length ? [...navigator.languages] : [];
  return list.length ? list : navigator.language ? [navigator.language] : [];
}

export const detectPriveLang = (profile?: string | null): PriveLang => resolvePriveLang({ profile, languages: browserLanguages() });

